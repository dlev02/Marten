// This worker displays notifications requested by an open Marten tab. It does
// not cache financial data or subscribe this device to a Web Push service.
self.addEventListener("install", (event) =>
  event.waitUntil(self.skipWaiting()),
);
self.addEventListener("activate", (event) =>
  event.waitUntil(self.clients.claim()),
);
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  event.waitUntil(
    (async () => {
      const windows = await self.clients.matchAll({
        type: "window",
        includeUncontrolled: true,
      });
      const existing = windows.find(
        (client) => new URL(client.url).origin === self.location.origin,
      );
      if (existing) {
        await existing.navigate("/recurring");
        await existing.focus();
      } else {
        await self.clients.openWindow("/recurring");
      }
    })(),
  );
});
